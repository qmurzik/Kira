// Signing config is read from environment variables (CI) or a local
// keystore.properties file (never committed - see .gitignore) so that
// no secrets ever live in source control. See README.md "Release signing".
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        load(keystorePropertiesFile.inputStream())
    }
}

fun signingProp(name: String): String? =
    keystoreProperties.getProperty(name) ?: System.getenv(name)

